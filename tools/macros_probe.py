#!/usr/bin/env python3
"""Check the value macros of raylib.h, raymath.h, rlgl.h, rcamera.h and rgestures.h as Jonlib constants.

A macro whose value is an integer, a float (`f` suffix), a double or a string
literal, or the name of an enumerator (MOUSE_LEFT_BUTTON is MOUSE_BUTTON_LEFT),
is a zero-argument function in the generated section of jonlib.bend just
before the enumerations, named as the ledger proposes for its work package
(tools/api_plan.py): `Rlgl.RL_TEXTURE_WRAP_S()`, `Config.MOUSE_LEFT_BUTTON()`,
`Config.JONLIB_VERSION()` (raylib's RAYLIB_VERSION, branded as docs/MODULES.md
names project configuration), `Math.PI()`. U32 for an int, F32 for a float,
M.Float64 for a double and String for a string. Macros mapped elsewhere (the color
macros, raylib's and raymath's PI, DEG2RAD, RAD2DEG and EPSILON) are not
generated, nor are guards, function-like macros and macros naming functions or
types. Each header compiles standalone in Jonlib's configuration (rlgl.h with
GRAPHICS_API_OPENGL_SOFTWARE, rcamera.h and rgestures.h with their *_STANDALONE
switch) and prints its values; the gate compares every generated constant on
CPU-1, CPU-2 and JavaScript, and fails when the catalog and the generated
section disagree. `--write` regenerates the section from api/reference.json and
the native values.
"""
import json
import re

import api_plan
import probekit
from probekit import ROOT, ProbeFailure

RULE = '# -----------------------------------------------------------------------------'
TITLE = '# Header macros (generated by tools/macros_probe.py --write)'
ENUMS_TITLE = '# Header enumerations (generated by tools/enums_probe.py --write)'
NOTE = '''#
# Each value macro is a constant named as the API ledger proposes for its
# work package (Rlgl.*, Config.*, Math.*): U32 for an int, F32 for a float,
# M.Float64 for a double and String for a string; a macro naming an
# enumerator has the enumerator's value.
'''
# header: (prefix lines of its standalone program, linked against raylib)
HEADERS = {
    'raylib.h': (['#include "raylib.h"'], True),
    'raymath.h': (['#include "raymath.h"'], False),
    'rlgl.h': (['#define GRAPHICS_API_OPENGL_SOFTWARE', '#include "rlgl.h"'], False),
    'rcamera.h': (['#include <stdbool.h>', '#define RCAMERA_STANDALONE', '#include "rcamera.h"'], False),
    'rgestures.h': (['#define RGESTURES_STANDALONE', '#include "rgestures.h"'], False),
}
# Mapped elsewhere: Jonmath's M.Math constants (tools/constants_probe.py).
ELSEWHERE = {('raylib.h', name) for name in ('PI', 'DEG2RAD', 'RAD2DEG')} | {('raymath.h', name) for name in ('PI', 'EPSILON', 'DEG2RAD', 'RAD2DEG')}
INT = re.compile(r'^(0[xX][0-9A-Fa-f]+|\d+)$')
FLOAT = re.compile(r'^\d+\.\d*([eE][+-]?\d+)?[fF]$')
DOUBLE = re.compile(r'^\d+\.\d*([eE][+-]?\d+)?$')
STRING = re.compile(r'^"[^"\\]*"$')
NAME = re.compile(r'^[A-Z][A-Z0-9_]*$')


def catalog():
    entries = json.loads((ROOT / 'api/reference.json').read_text())['entries']
    return entries if isinstance(entries, list) else list(entries.values())


def kind_of(value, enumerators):
    if INT.match(value):
        return 'int'
    if FLOAT.match(value):
        return 'float'
    if DOUBLE.match(value):
        return 'double'
    if STRING.match(value):
        return 'string'
    if NAME.match(value) and value in enumerators:
        return 'int'
    return None


def milestones():
    return {item['id']: item for item in json.loads((ROOT / 'api/milestones.json').read_text())['milestones']}


def bend_name(row, plan=None):
    """The ledger's proposed Jonlib name of a catalog row."""
    plan = milestones() if plan is None else plan
    return api_plan.proposed(row, plan[api_plan.classify(row)])


def macros(rows=None):
    """[(header, name, kind, bend name)] in catalog order."""
    rows = catalog() if rows is None else rows
    plan = milestones()
    enumerators = {row['name'] for row in rows if row['kind'] == 'enumerator'}
    out, seen = [], set()
    for row in rows:
        if row['kind'] != 'macro' or row['header'] not in HEADERS or (row['header'], row['name']) in ELSEWHERE:
            continue
        variant = (row.get('variants') or [{}])[0]
        if variant.get('parameters') is not None:
            continue
        kind = kind_of((variant.get('value') or '').strip(), enumerators)
        if kind and (row['header'], row['name']) not in seen:
            seen.add((row['header'], row['name']))
            out.append((row['header'], row['name'], kind, bend_name(row, plan)))
    out = sorted(out, key=lambda key: list(HEADERS).index(key[0]))
    names = [key[3] for key in out]
    if len(set(names)) != len(names):
        raise ProbeFailure(f'macros: two macros share a Jonlib name: {sorted(n for n in names if names.count(n) > 1)}')
    return out


def prefix(header):
    return header.split('.')[0]


C_PRINT = {
    'int': 'printf("%lld\\n",(long long)({name}));',
    'float': '{{float f=({name});unsigned u;memcpy(&u,&f,4);printf("%u\\n",u);}}',
    'double': '{{double d=({name});unsigned long long u;memcpy(&u,&d,8);printf("%u %u\\n",(unsigned)(u>>32),(unsigned)u);}}',
    'string': 'printf("%s\\n",{name});',
}


def native_values(probe, selected):
    """{(header, name): printed text} from one standalone program per header."""
    values = {}
    for header, (prefix_lines, linked) in HEADERS.items():
        chosen = [key for key in selected if key[0] == header]
        if not chosen:
            continue
        lines = prefix_lines + ['#include <stdio.h>', '#include <string.h>', 'int main(void){']
        lines += [C_PRINT[kind].format(name=name) for _, name, kind, _ in chosen]
        text = probe.native('\n'.join(lines + ['return 0;}']) + '\n', 'reference-' + prefix(header), link_raylib=linked)
        found = text.split('\n')[:-1]
        if len(found) != len(chosen):
            raise ProbeFailure(f'macros: {header} printed {len(found)} values for {len(chosen)} macros')
        for (h, name, kind, _), value in zip(chosen, found):
            if kind == 'int' and not (0 <= int(value) <= 0xFFFFFFFF or -0x80000000 <= int(value) < 0):
                raise ProbeFailure(f'macros: {name} = {value} is outside a 32-bit word')
            values[(h, name)] = str(int(value) & 0xFFFFFFFF) if kind == 'int' else value
    return values


def bend_value(kind, text):
    if kind == 'int':
        return 'U32', text
    if kind == 'float':
        return 'F32', f'Macros.f32({text})'
    if kind == 'double':
        high, low = text.split()
        return 'M.Float64', f'M.Float64{{{high}, {low}}}'
    return 'String', json.dumps(text)


def section(generated):
    text = '\n' + RULE + '\n' + TITLE + '\n' + NOTE + '''
def Macros.f32(+bits: U32) -> F32:
  U32{b} = bits
  F32{b}
'''
    current = None
    for header, name, kind, bend, value in generated:
        if header != current:
            text += f'\n# {header}\n'
            current = header
        typ, body = bend_value(kind, value)
        text += f'# {name}\ndef {bend}() -> {typ}:\n  {body}\n'
    return text


def write(generated):
    path = ROOT / 'jonlib.bend'
    source = path.read_text()
    enums = '\n' + RULE + '\n' + ENUMS_TITLE
    if enums not in source:
        raise ProbeFailure('macros: the enumeration section is missing; the macro section goes before it')
    head, tail = source.split(enums, 1)
    marker = '\n' + RULE + '\n' + TITLE
    if marker in head:
        head = head[:head.index(marker)]
    path.write_text(head.rstrip('\n') + '\n' + section(generated) + enums + tail)


def check_generated(generated):
    source = (ROOT / 'jonlib.bend').read_text()
    if TITLE not in source:
        raise ProbeFailure('macros: the jonlib.bend section is missing; rerun tools/macros_probe.py --write')
    body = source.split(TITLE, 1)[1].split(ENUMS_TITLE, 1)[0]
    found = [line[4:line.index('(')] for line in body.splitlines() if line.startswith('def ') and not line.startswith('def Macros.')]
    if found != [bend for _, _, _, bend, _ in generated]:
        raise ProbeFailure('macros: the generated jonlib.bend section is stale; rerun tools/macros_probe.py --write')


SHOW = {'int': 'U32.show(J.{c}())', 'float': 'U32.show(F32.bits(J.{c}()))', 'double': 'show64(J.{c}())', 'string': 'J.{c}()'}


def render(selected, gpu):
    body = ('import Base\nimport ../../jonlib.bend as J\nimport ../../jonmath.bend as M\n'
            'def show64(value: M.Float64) -> String:\n  M.Float64{high, low} = value\n  U32.show(high) ++ " " ++ U32.show(low)\n'
            'def main() -> IO(Unit):\n  do IO<Unit>:\n')
    for _, _, kind, bend, _ in selected:
        body += f'    IO.print({SHOW[kind].format(c=bend)})\n'
    return body + '    IO.print("done")\n'


def parse(text, selected):
    lines = text.split('\n')
    if len(lines) < 2 or lines[-2] != 'done':
        raise ProbeFailure(f'macros: the candidate did not finish: {text[-300:]!r}')
    return lines[:-2]


def main():
    def configure(parser):
        parser.add_argument('--write', action='store_true', help='Regenerate the jonlib.bend macro section')
    args = probekit.arguments(__doc__, configure)
    probe = probekit.Probe('macros', args)
    selected = macros()
    values = native_values(probe, selected)
    generated = [(header, name, kind, bend, values[(header, name)]) for header, name, kind, bend in selected]
    if args.write:
        write(generated)
    check_generated(generated)
    lanes = probe.candidates(render, generated, batch=200, parse=parse)
    lanes = {lane: rows for lane, rows in lanes.items() if lane != 'gpu'}
    probe.compare([value for _, _, _, _, value in generated], lanes, describe=lambda i: '.'.join(generated[i][:2]))
    probe.finish(macros=len(generated), kinds={kind: sum(k == kind for _, _, k, _, _ in generated) for kind in C_PRINT},
                 headers={header: sum(h == header for h, _, _, _, _ in generated) for header in HEADERS})


if __name__ == '__main__':
    main()
