# glyf

def simple_glyph(contours, bbox=None, instructions=b'', compress=True):
    """contours: [[(x, y, on), ...], ...]"""
    pts = [p for c in contours for p in c]
    if not pts:
        return b''
    ends, k = [], -1
    for c in contours:
        k += len(c)
        ends.append(k)
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    if bbox is None:
        bbox = (min(xs), min(ys), max(xs), max(ys))
    flags, xdata, ydata = [], b'', b''
    px = py = 0
    for x, y, on in pts:
        f = 1 if on else 0
        dx, dy = x - px, y - py
        if compress and dx == 0:
            f |= 16
        elif compress and -255 <= dx <= 255:
            f |= 2 | (16 if dx > 0 else 0)
            xdata += bytes([abs(dx)])
        else:
            xdata += struct.pack('>h', dx)
        if compress and dy == 0:
            f |= 32
        elif compress and -255 <= dy <= 255:
            f |= 4 | (32 if dy > 0 else 0)
            ydata += bytes([abs(dy)])
        else:
            ydata += struct.pack('>h', dy)
        flags.append(f)
        px, py = x, y
    fdata, i = b'', 0
    while i < len(flags):
        run = 1
        while compress and i + run < len(flags) and flags[i + run] == flags[i] and run < 256:
            run += 1
        if run > 1:
            fdata += bytes([flags[i] | 8, run - 1])
        else:
            fdata += bytes([flags[i]])
        i += run
    out = struct.pack('>hhhhh', len(contours), *bbox)
    out += b''.join(struct.pack('>H', e) for e in ends)
    out += struct.pack('>H', len(instructions)) + instructions
    return out + fdata + xdata + ydata


def composite_glyph(components, bbox=(0, 0, 100, 100)):
    """components: dicts with gidx, dx, dy and optional words (bool), scale
    (one value), xy (two), two (four) as F2DOT14 ints, point (matching-point form)."""
    out = struct.pack('>hhhhh', -1, *bbox)
    for i, c in enumerate(components):
        flags = 0
        more = i + 1 < len(components)
        args = b''
        if c.get('point'):
            flags |= 0
            args = struct.pack('>BB', c['dx'] & 0xFF, c['dy'] & 0xFF)
        else:
            flags |= 2
            if c.get('words') or not (-128 <= c['dx'] <= 127 and -128 <= c['dy'] <= 127):
                flags |= 1
                args = struct.pack('>hh', c['dx'], c['dy'])
            else:
                args = struct.pack('>bb', c['dx'], c['dy'])
        tail = b''
        if 'scale' in c:
            flags |= 8
            tail = struct.pack('>h', c['scale'])
        elif 'xy' in c:
            flags |= 64
            tail = struct.pack('>hh', *c['xy'])
        elif 'two' in c:
            flags |= 128
            tail = struct.pack('>hhhh', *c['two'])
        if more:
            flags |= 32
        out += struct.pack('>HH', flags, c['gidx']) + args + tail
    return out


def glyf_loca(glyphs, loc_format):
    glyf, offsets = b'', []
    for g in glyphs:
        offsets.append(len(glyf))
        glyf += g + b'\0' * (len(g) % 2 if loc_format == 0 else -len(g) % 4)
    offsets.append(len(glyf))
    if loc_format == 0:
        loca = b''.join(struct.pack('>H', o // 2) for o in offsets)
    else:
        loca = b''.join(struct.pack('>I', o) for o in offsets)
    return glyf, loca


