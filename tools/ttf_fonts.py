# Outlines

def random_contours(rng, em, kind):
    """Seeded contours in [0, em) squares: kind 'curves', 'lines' or 'mixed'."""
    contours = []
    for _ in range(rng.randint(1, 3)):
        cx, cy = rng.randint(em // 8, em * 5 // 8), rng.randint(-em // 8, em * 5 // 8)
        r = rng.randint(em // 12, em // 3)
        n = rng.randint(3, 9)
        pts = []
        for k in range(n):
            import math
            a = 2 * math.pi * k / n + rng.uniform(-0.3, 0.3)
            rr = r * rng.uniform(0.4, 1.1)
            on = True if kind == 'lines' else (rng.random() < (0.5 if kind == 'mixed' else 0.35))
            pts.append((int(cx + rr * math.cos(a)), int(cy + rr * math.sin(a)), on))
        if rng.random() < 0.5:
            pts.reverse()
        contours.append(pts)
    if kind != 'lines' and rng.random() < 0.3:
        # a single-point contour; off the curve it reads the next contour's
        # first point, so it never comes last (stb would read past the points)
        contours.insert(rng.randrange(len(contours)), [(rng.randint(0, em // 2), rng.randint(0, em // 2), rng.random() < 0.5)])
    return contours


def box_contours(rng, em):
    """Pixel-font style rectangles (lines only, axis-aligned edges)."""
    cell = em // 8
    out = []
    for _ in range(rng.randint(1, 4)):
        x, y = rng.randint(0, 5) * cell, rng.randint(-1, 5) * cell
        w, h = rng.randint(1, 3) * cell, rng.randint(1, 3) * cell
        out.append([(x, y, True), (x, y + h, True), (x + w, y + h, True), (x + w, y, True)])
    return out


def build_font(seed, *, em=1000, codepoints=range(32, 127), cmap='4', loc_format=0, kind='mixed',
               ascent=None, descent=None, line_gap=0, long_metrics=None, extra_glyphs=(), composites=True,
               bad_bbox=0.0, empty=(32,), compress=True, extra_tables=None):
    """A complete TrueType font; returns (bytes, {codepoint: glyph index})."""
    rng = random.Random(seed)
    glyphs = [simple_glyph([[(0, 0, True), (em // 2, 0, True), (em // 2, em // 2, True), (0, em // 2, True)]])]  # .notdef
    advances, lsbs = [em // 2], [0]
    mapping = {}
    for cp in codepoints:
        if cp in empty:
            data = b''
        elif kind == 'boxes':
            data = simple_glyph(box_contours(rng, em), compress=compress)
        else:
            contours = random_contours(rng, em, kind)
            bbox = None
            if rng.random() < bad_bbox:
                xs = [p[0] for c in contours for p in c]
                ys = [p[1] for c in contours for p in c]
                shrink = rng.randint(em // 20, em // 6)
                bbox = (min(xs) + shrink, min(ys) + shrink // 2, max(xs) - shrink, max(ys) - shrink // 3)
            data = simple_glyph(contours, bbox=bbox, compress=compress)
        mapping[cp] = len(glyphs)
        glyphs.append(data)
        advances.append(rng.randint(em // 4, em) if cp not in empty or rng.random() < 0.8 else 0)
        lsbs.append(rng.randint(-20, 40))
    if composites:
        simple = [mapping[c] for c in codepoints if c not in empty]
        comps = [
            [dict(gidx=simple[0], dx=10, dy=-5)],
            [dict(gidx=simple[1], dx=200, dy=-300, words=True), dict(gidx=simple[2], dx=-40, dy=60)],
            [dict(gidx=simple[3], dx=0, dy=0, scale=8192)],
            [dict(gidx=simple[4], dx=30, dy=20, xy=(20000, 12000))],
            [dict(gidx=simple[5], dx=-10, dy=100, two=(14000, 3000, -4000, 15000))],
            [dict(gidx=simple[6], dx=5, dy=5), dict(gidx=simple[7], dx=300, dy=0, scale=-16384)],
        ]
        for spec in comps:
            mapping[0x100 + len(glyphs)] = len(glyphs)
            glyphs.append(composite_glyph(spec))
        nested = len(glyphs)
        mapping[0x100 + nested] = nested
        glyphs.append(composite_glyph([dict(gidx=nested - 1, dx=50, dy=50), dict(gidx=simple[8], dx=-20, dy=-20, scale=12000)]))
        mapping[0x100 + len(glyphs)] = len(glyphs)
        glyphs.append(composite_glyph([dict(gidx=simple[9], dx=3, dy=4, point=True), dict(gidx=simple[10], dx=100, dy=0)]))
    for cp, data in extra_glyphs:
        mapping[cp] = len(glyphs)
        glyphs.append(data)
        advances.append(rng.randint(em // 4, em))
        lsbs.append(0)
    while len(advances) < len(glyphs):
        advances.append(rng.randint(em // 4, em))
        lsbs.append(rng.randint(-20, 40))
    n = len(glyphs)
    long_metrics = n if long_metrics is None else long_metrics
    glyf, loca = glyf_loca(glyphs, loc_format)
    ascent = em * 4 // 5 if ascent is None else ascent
    descent = -em // 5 if descent is None else descent
    if cmap == '4':
        sub = [(3, 1, cmap_format4({c: g for c, g in mapping.items() if c <= 0xFFFF}))]
    elif cmap == '4r':
        sub = [(0, 3, cmap_format4({c: g for c, g in mapping.items() if c <= 0xFFFF}, use_delta=False))]
    elif cmap == '0':
        sub = [(0, 0, cmap_format0({c: g for c, g in mapping.items() if c < 256}))]
    elif cmap == '6':
        first = min(mapping)
        count = min(max(c for c in mapping if c < 0x10000) - first + 1, 400)
        sub = [(3, 1, cmap_format6(mapping, first, count))]
    elif cmap in ('12', '13'):
        sub = [(1, 0, cmap_format0({})), (3, 10, cmap_format12(mapping, int(cmap)))]
    elif cmap == '2':
        sub = [(3, 1, struct.pack('>HHH', 2, 6, 0))]
    else:
        raise ValueError(cmap)
    tables = {'head': head_table(em, loc_format), 'hhea': hhea_table(ascent, descent, line_gap, long_metrics),
              'maxp': maxp_table(n), 'hmtx': hmtx_table(advances, lsbs, long_metrics), 'cmap': cmap_table(sub),
              'loca': loca, 'glyf': glyf}
    if extra_tables:
        tables.update(extra_tables)
    return sfnt(tables), mapping
