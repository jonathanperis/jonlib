#!/usr/bin/env python3
"""Generate the header modules jonlgl.bend, joncamera.bend and jongestures.bend.

rlgl.h, rcamera.h and rgestures.h are adapted inside jonlib.bend (Jonlib's
drawing is built on them, so they cannot sit below it without an import
cycle). Each header's module is generated from the API ledger: every Jonlib
name the ledger maps one of the header's entries to (functions, enumerators,
macros) becomes a definition of the same name and signature that calls
Jonlib's, with Jonlib's own types written J.<Type>. `--check` fails when a
module is stale.
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = {
    'jonlgl.bend': ('rlgl', 'rlgl.h', 'Jonlgl', 'rlgl v6.0 (raylib 6.2 src/rlgl.h)', 'RLGL.md'),
    'joncamera.bend': ('rcamera', 'rcamera.h', 'Joncamera', 'rcamera (raylib 6.2 src/rcamera.h)', 'CAMERA.md'),
    'jongestures.bend': ('rgestures', 'rgestures.h', 'Jongestures', 'rgestures (raylib 6.2 src/rgestures.h)', 'INPUT.md'),
}
DEF = re.compile(r'^def ([\w.]+)\((.*)\) -> (.+):$')
TYPE = re.compile(r'^type ([\w.]+)(?:\(.*\))? is ')
IDENT = re.compile(r'[A-Za-z_][\w.]*')


def ledger_names(prefix):
    entries = json.loads((ROOT / 'api/progress.json').read_text())
    entries = entries.get('entries', entries)
    names = []
    for key, entry in entries.items():
        # Types stay Jonlib's and Jonmath's (J.Frame, M.Vector3): a module cannot re-export a type.
        if not key.startswith(prefix + ':') or key.split(':')[1] in ('type', 'alias') or entry.get('status') not in ('partial', 'complete'):
            continue
        for part in entry.get('jonlib', '').split(' / '):
            part = part.strip()
            # Base's and Jonmath's types (a type guard's counterpart) are no Jonlib definitions.
            if part == 'Bool' or part.startswith(('M.', 'jonmath.')):
                continue
            if re.fullmatch(r'[A-Za-z][\w.]*', part) and part not in names:
                names.append(part)
    return names


def jonlib_index(source):
    defs, types = {}, set()
    for line in source.splitlines():
        match = DEF.match(line)
        if match:
            defs.setdefault(match[1], (match[2], match[3]))
        match = TYPE.match(line)
        if match:
            types.add(match[1])
    imports = [line for line in source.splitlines() if line.startswith('import ')]
    return defs, types, imports


def qualify(text, types):
    return IDENT.sub(lambda m: 'J.' + m[0] if m[0] in types else m[0], text)


def split_params(params):
    out, depth, current = [], 0, ''
    for ch in params:
        if ch in '<(':
            depth += 1
        elif ch in '>)':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(current.strip())
            current = ''
        else:
            current += ch
    if current.strip():
        out.append(current.strip())
    return out


def wrapper(name, params, result, types):
    parts = split_params(params)
    args = []
    for part in parts:
        binder, _, typ = part.partition(':')
        args.append(binder.strip().lstrip('+~-&'))
    qualified = ', '.join(qualify(part, types) for part in parts)
    return f'def {name}({qualified}) -> {qualify(result, types)}:\n  J.{name}({", ".join(args)})\n'


def generate(module):
    prefix, header, title, upstream, doc = MODULES[module]
    source = (ROOT / 'jonlib.bend').read_text()
    defs, types, imports = jonlib_index(source)
    names = ledger_names(prefix)
    missing = [n for n in names if n not in defs]
    if missing:
        raise SystemExit(f'{module}: the ledger names definitions jonlib.bend lacks: {missing[:10]}')
    lines = [f'# {title} - zlib license, Copyright (c) 2026 Jonathan Peris.',
             f'# Generated by tools/facades.py from api/progress.json: {header}\'s API as its own',
             f'# module. {upstream} is adapted inside jonlib.bend, whose drawing is built on it;',
             f'# each definition here has the name and signature of the Jonlib one it calls.',
             f'# See docs/{doc} and docs/MODULES.md.',
             'import Base', 'import ./jonlib.bend as J'] + [line for line in imports]
    body = [wrapper(name, *defs[name], types) for name in names]
    return '\n'.join(lines) + '\n\n' + '\n'.join(body)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = []
    for module in MODULES:
        text = generate(module)
        path = ROOT / module
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(module)
        else:
            path.write_text(text)
    if stale:
        sys.exit(f'facades: stale {stale}; rerun tools/facades.py')
    print('facades: ' + ', '.join(f'{m} ({generate(m).count(chr(10) + "def ")} definitions)' for m in MODULES))


if __name__ == '__main__':
    main()
