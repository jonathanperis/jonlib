#!/usr/bin/env python3
"""Generate src/mp3_tables.bend from pinned raylib's src/external/dr_mp3.h.

dr_mp3's decoder (minimp3) reads its constants from `static const` tables in
the header. This tool takes the tables src/mp3_layer3.bend uses out of the
header's text, compiles them into a small C program that prints every element
(an integer as it is, a float as its binary32 bits: the C compiler converts
each literal, as it does for raylib), checks what the port relies on and
writes the Bend module. Nothing is typed by hand.

  python3 tools/mp3_tables.py --raylib-source <raylib>           write the module
  python3 tools/mp3_tables.py --raylib-source <raylib> --check   fail if it is stale

The mp3-layer3 gate runs the same check with its own compiler run.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = 'src/external/dr_mp3.h'
MODULE = ROOT / 'src' / 'mp3_tables.bend'

# The tables taken, with their C element type and element count in dr_mp3
# v0.7.4. A header that declares another count is not the one this was
# written for.
TABLES = {
    'g_scf_long': ('drmp3_uint8', 8 * 23), 'g_scf_short': ('drmp3_uint8', 8 * 40), 'g_scf_mixed': ('drmp3_uint8', 8 * 40),
    'g_scf_partitions': ('drmp3_uint8', 3 * 28), 'g_scfc_decode': ('drmp3_uint8', 16), 'g_mod': ('drmp3_uint8', 24),
    'g_preamp': ('drmp3_uint8', 10), 'g_expfrac': ('float', 4), 'g_drmp3_pow43': ('float', 145), 'tabs': ('drmp3_int16', 2164),
    'tab32': ('drmp3_uint8', 28), 'tab33': ('drmp3_uint8', 16), 'tabindex': ('drmp3_int16', 32), 'g_linbits': ('drmp3_uint8', 32),
    'g_pan': ('float', 14),
    'g_aa': ('float', 16), 'g_twid9': ('float', 18), 'g_twid3': ('float', 6), 'g_mdct_window': ('float', 36),
}

# The float literals of drmp3_L3_dct3_9 and drmp3_L3_idct3 (cosines of 10 to
# 80 degrees), by the name they get in the module. They are in the functions'
# bodies, not in tables: each must be in the header's text, and the C
# compiler converts them like the tables' floats.
CONSTANTS = {'cos10': '0.98480775f', 'cos20': '0.93969262f', 'cos30': '0.86602540f', 'cos40': '0.76604444f', 'cos50': '0.64278761f', 'cos70': '0.34202014f',
             'cos80': '0.17364818f'}

DECLARATION = re.compile(r'static const (float|drmp3_uint8|drmp3_int16)\s+(\w+)((?:\[[^\]]*\])+)\s*=\s*\{(.*?)\};', re.S)

PREAMBLE = '''# Generated by tools/mp3_tables.py from pinned raylib's src/external/dr_mp3.h
# (dr_mp3 v0.7.4, David Reid; its decoder and these tables are minimp3's, by
# lieff): do not edit by hand. See THIRD_PARTY_NOTICES.md and
# LICENSES/dr_mp3.txt.
#
# Integers are as in the header; an int16 is its 16-bit pattern (a negative
# Huffman entry is 32768 and more). A float is its binary32 bits, as the C
# compiler converts the header's literal.
import Base
'''


def program(header):
    """A C program that prints `name count values...` for every table of TABLES found in the header's text."""
    found = {}
    for kind, name, dims, body in DECLARATION.findall(header):
        if name in TABLES:
            found.setdefault(name, (kind, dims, body))
    missing = sorted(set(TABLES) - set(found))
    if missing:
        raise ValueError(f'mp3 tables: dr_mp3.h does not declare {", ".join(missing)}')
    lines = ['#include <stdio.h>', '#include <string.h>', 'typedef unsigned char drmp3_uint8; typedef short drmp3_int16;', 'int main(void)', '{']
    for name, (kind, dims, body) in found.items():
        if kind != TABLES[name][0]:
            raise ValueError(f'mp3 tables: {name} is {kind}, expected {TABLES[name][0]}')
        lines.append(f'    {{ static const {kind} t{dims} = {{{body}}}; const {kind} *p = (const {kind} *)t; unsigned n = sizeof(t)/sizeof({kind}); printf("{name} %u", n);')
        if kind == 'float':
            lines.append('      for (unsigned i = 0; i < n; i++) { unsigned w; memcpy(&w, &p[i], 4); printf(" %u", w); } printf("\\n"); }')
        else:
            lines.append('      for (unsigned i = 0; i < n; i++) printf(" %d", (int)p[i]); printf("\\n"); }')
    absent = sorted(literal for literal in CONSTANTS.values() if literal not in header)
    if absent:
        raise ValueError(f'mp3 tables: dr_mp3.h does not have the literal {", ".join(absent)}')
    lines.append(f'    {{ static const float t[] = {{{", ".join(CONSTANTS.values())}}}; printf("constants {len(CONSTANTS)}");')
    lines.append(f'      for (unsigned i = 0; i < {len(CONSTANTS)}; i++) {{ unsigned w; memcpy(&w, &t[i], 4); printf(" %u", w); }} printf("\\n"); }}')
    return '\n'.join(lines + ['    return 0;', '}']) + '\n'


def parse(text):
    """name -> values, from the program's output; every table of TABLES with its count, and `constants`."""
    tables, sizes = {}, dict({name: count for name, (_, count) in TABLES.items()}, constants=len(CONSTANTS))
    for line in text.splitlines():
        name, count, *values = line.split()
        if name not in sizes or len(values) != int(count) or int(count) != sizes[name]:
            raise ValueError(f'mp3 tables: {name} has {count} elements, not the {sizes.get(name, "?")} of dr_mp3 v0.7.4')
        tables[name] = [int(v) for v in values]
    if set(tables) != set(sizes):
        raise ValueError('mp3 tables: the program did not print every table')
    return tables


def trees(tables):
    """For every codebook: (deepest entry chain, longest code, highest bs_sh at a DRMP3_CHECK_BITS), walking each tree whole.

    Raises ValueError where a walk would leave `tabs`, peek no bits or flush more bits than it peeked."""
    tabs, out = tables['tabs'], []
    for number in range(32):
        base, linbits, depth, leaves = tables['tabindex'][number], tables['g_linbits'][number], 0, []
        stack = [(base + i, 5, 0, 1) for i in range(32)]
        while stack:
            index, width, flushed, level = stack.pop()
            if not 0 <= index < len(tabs) or level > 16:
                raise ValueError(f'mp3 tables: codebook {number} leaves tabs')
            leaf, depth = tabs[index], max(depth, level)
            if leaf < 0:
                if leaf & 7 == 0:
                    raise ValueError(f'mp3 tables: codebook {number} peeks no bits')
                stack += [(base + bits - (leaf >> 3), leaf & 7, flushed + width, level + 1) for bits in range(1 << (leaf & 7))]
            else:
                if (leaf >> 8) > width:
                    raise ValueError(f'mp3 tables: codebook {number} flushes more bits than it peeked')
                leaves.append((flushed + (leaf >> 8), leaf & 15, (leaf >> 4) & 15))
        escaped = lambda lsb: bool(linbits) and lsb == 15
        # bs_sh is at most -1 after a check; a pair flushes its code, then for each value its linbits or its sign bit
        checks = [-1 + code + linbits for code, a, b in leaves if escaped(a)]
        checks += [-1 + code + (1 if a else 0) + linbits for code, a, b in leaves if escaped(b) and not escaped(a)]
        checks += [-1 + code + sum((1 if escaped(v) else 1 if v else 0) for v in (a, b)) for code, a, b in leaves]
        out.append((depth, max(code for code, _, _ in leaves), max(checks)))
    return out


def verify(tables):
    """What src/mp3_layer3.bend relies on; ValueError where a table does not have it.

    Every band table's widths are even and add up to a granule's 576 values, so
    the big values (at most 288 pairs) end before the bands do and no band has
    no pair; a codebook's tree is at most six entries deep (the walk's fuel) and
    within `tabs`; the cache never needs a shift of 32 bits or more; a count1
    leaf of tab32 that sends on peeks one to three more bits and stays in it."""
    for name, width in (('g_scf_long', 23), ('g_scf_short', 40), ('g_scf_mixed', 40)):
        flat = tables[name]
        for at in range(0, len(flat), width):
            row = flat[at:at + width]
            bands = row[:row.index(0)] if 0 in row else row
            if 0 not in row or sum(bands) != 576 or any(v % 2 for v in bands) or any(row[len(bands):]):
                raise ValueError(f'mp3 tables: {name} row {at // width} is not 576 values in even bands and a 0')
    for number, (depth, code, shift) in enumerate(trees(tables)):
        if depth > 6 or shift > 31:
            raise ValueError(f'mp3 tables: codebook {number} is {depth} entries deep and shifts by {shift}')
    for name in ('tab32', 'tab33'):
        tab = tables[name]
        for leaf in tab[:16]:
            if not leaf & 8 and (leaf & 3 == 0 or (leaf >> 3) + (1 << (leaf & 3)) > len(tab)):
                raise ValueError(f'mp3 tables: {name} sends a count1 code outside itself')
    if len(tables['g_drmp3_pow43']) != 145:
        raise ValueError('mp3 tables: g_drmp3_pow43 is not 16 negative values and 129')


def flat(values):
    lines, line = [], ''
    for value in values:
        piece = f'{value}, '
        if len(line) + len(piece) > 150:
            lines.append(line.rstrip())
            line = ''
        line += piece
    lines.append(line.rstrip().rstrip(','))
    return '[' + '\n    '.join(lines) + ']'


def rows(values, width):
    return '[' + ',\n    '.join('[' + ', '.join(str(v) for v in values[at:at + width]) + ']' for at in range(0, len(values), width)) + ']'


def render(tables):
    """The text of src/mp3_tables.bend."""
    verify(tables)
    out = [PREAMBLE]

    def table(name, comment, kind, body):
        out.append(f'# {comment}\ndef {name}() -> {kind}:\n  {body}\n')

    table('scf.long', "g_scf_long: the long blocks' scalefactor band widths, a row a sample rate.", '+List<+List<U32>>', rows(tables['g_scf_long'], 23))
    table('scf.short', "g_scf_short: the short blocks'.", '+List<+List<U32>>', rows(tables['g_scf_short'], 40))
    table('scf.mixed', "g_scf_mixed: the mixed blocks'.", '+List<+List<U32>>', rows(tables['g_scf_mixed'], 40))
    table('scf.partitions', 'g_scf_partitions: the scalefactor counts, for long, mixed and short blocks.', '+List<+List<U32>>', rows(tables['g_scf_partitions'], 28))
    table('scfc.decode', 'g_scfc_decode.', '+List<U32>', flat(tables['g_scfc_decode']))
    table('mod', 'g_mod.', '+List<U32>', flat(tables['g_mod']))
    table('preamp', 'g_preamp.', '+List<U32>', flat(tables['g_preamp']))
    table('expfrac', 'g_expfrac (floats).', '+List<U32>', flat(tables['g_expfrac']))
    table('pow43', 'g_drmp3_pow43 (floats): 16 negative values, then x^(4/3) for 0..128.', '+List<U32>', flat(tables['g_drmp3_pow43']))
    index, tabs = tables['tabindex'], tables['tabs']
    starts = sorted(set(index))
    for start, end in zip(starts, starts[1:] + [len(tabs)]):
        table(f'tabs.at{start}', f'tabs from {start}: the Huffman table of the codebooks whose tabindex is {start}.', '+List<U32>', flat([v & 0xFFFF for v in tabs[start:end]]))
    out.append('# The Huffman table of a codebook (table_select): tabs from tabindex[tab].\ndef book(tab: U32) -> +List<U32>:\n  match tab:\n'
               + ''.join(f'    case {number}: tabs.at{index[number]}()\n' for number in range(31)) + f'    case _: tabs.at{index[31]}()\n')
    table('tab32', 'tab32.', '+List<U32>', flat(tables['tab32']))
    table('tab33', 'tab33.', '+List<U32>', flat(tables['tab33']))
    table('linbits', 'g_linbits.', '+List<U32>', flat(tables['g_linbits']))
    table('pan', 'g_pan (floats): kl and kr of the seven MPEG-1 intensity positions.', '+List<U32>', flat(tables['g_pan']))
    table('aa', 'g_aa (floats): two rows of eight.', '+List<+List<U32>>', rows(tables['g_aa'], 8))
    table('twid9', 'g_twid9 (floats).', '+List<U32>', flat(tables['g_twid9']))
    table('twid3', 'g_twid3 (floats).', '+List<U32>', flat(tables['g_twid3']))
    table('mdct.window', "g_mdct_window (floats): the long window and the stop block's, eighteen each.", '+List<+List<U32>>', rows(tables['g_mdct_window'], 18))
    for name, value in zip(CONSTANTS, tables['constants']):
        out.append(f'# {CONSTANTS[name]} (a float) of drmp3_L3_dct3_9 and drmp3_L3_idct3.\ndef c.{name}() -> U32:\n  {value}\n')
    return '\n'.join(out)


def stale(text):
    """Why src/mp3_tables.bend is not `text`, or None."""
    if not MODULE.exists():
        return f'{MODULE.relative_to(ROOT)} is missing'
    if MODULE.read_text() != text:
        return f'{MODULE.relative_to(ROOT)} is not what tools/mp3_tables.py generates from the pinned dr_mp3.h'
    return None


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--raylib-source', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='compare with src/mp3_tables.bend instead of writing it')
    args = parser.parse_args(argv)
    work = ROOT / '.build' / 'mp3-tables'
    work.mkdir(parents=True, exist_ok=True)
    (work / 'tables.c').write_text(program((args.raylib_source / HEADER).read_text()))
    subprocess.run(['clang', '-std=c11', '-O2', '-Wno-everything', work / 'tables.c', '-o', work / 'tables'], check=True)
    text = render(parse(subprocess.run([work / 'tables'], capture_output=True, text=True, check=True).stdout))
    if args.check:
        reason = stale(text)
        if reason:
            print(f'mp3 tables: {reason}', file=sys.stderr)
            return 1
        print('mp3 tables: src/mp3_tables.bend is current')
        return 0
    MODULE.write_text(text)
    print(f'mp3 tables: wrote {MODULE.relative_to(ROOT)} ({len(TABLES)} tables, {len(CONSTANTS)} constants)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
