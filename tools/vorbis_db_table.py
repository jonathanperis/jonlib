#!/usr/bin/env python3
"""Generate src/vorbis_db.bend from pinned raylib's src/external/stb_vorbis.c.

stb_vorbis's floors multiply the spectrum by inverse_db_table, 256 floats
the specification gives in decimal. This tool takes the table out of the
source's text, compiles it into a small C program that prints each element
as its binary32 bits (the C compiler converts each literal, as it does for
raylib), checks what the port relies on and writes the Bend module. Nothing
is typed by hand.

  python3 tools/vorbis_db_table.py --raylib-source <raylib>           write the module
  python3 tools/vorbis_db_table.py --raylib-source <raylib> --check   fail if it is stale

The vorbis-floor gate runs the same check with its own compiler run.
"""
import argparse
import re
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'src/external/stb_vorbis.c'
MODULE = ROOT / 'src' / 'vorbis_db.bend'
DECLARATION = re.compile(r'static float inverse_db_table\[256\]\s*=\s*\{(.*?)\};', re.S)

PREAMBLE = '''# Generated by tools/vorbis_db_table.py from pinned raylib's
# src/external/stb_vorbis.c (stb_vorbis v1.22, Sean Barrett; the table is
# the Vorbis I specification's): do not edit by hand. See
# THIRD_PARTY_NOTICES.md and LICENSES/stb_vorbis.txt.
#
# A float is its binary32 bits, as the C compiler converts the source's
# literal.
import Base

# inverse_db_table: what a floor's Y value (0 to 255) multiplies the
# spectrum by, from 1.0649863e-07 to 1.
def table() -> +List<U32>:
'''


def body(text):
    """The table's initializer in stb_vorbis.c's text."""
    found = DECLARATION.findall(text)
    if len(found) != 1:
        raise ValueError(f'stb_vorbis.c declares inverse_db_table {len(found)} times')
    return found[0]


def literals(text):
    """The 256 float literals of the table."""
    found = [token.strip() for token in body(text).split(',') if token.strip()]
    if len(found) != 256 or not all(re.fullmatch(r'[0-9.]+(e-[0-9]+)?f', token) for token in found):
        raise ValueError(f'inverse_db_table is not 256 float literals ({len(found)} tokens)')
    return found


def compiled(text):
    """The table's elements as binary32 bits, converted by the C compiler."""
    program = '#include <stdio.h>\n#include <string.h>\nstatic float inverse_db_table[256] = {' + body(text) + '''};
int main(void)
{
    for (int i = 0; i < 256; i++) { unsigned w; memcpy(&w, &inverse_db_table[i], 4); printf("%u\\n", w); }
    return 0;
}
'''
    with tempfile.TemporaryDirectory() as folder:
        source, binary = Path(folder) / 'table.c', Path(folder) / 'table'
        source.write_text(program)
        subprocess.run(['cc', '-std=c11', '-O0', str(source), '-o', str(binary)], check=True)
        return [int(line) for line in subprocess.run([str(binary)], check=True, capture_output=True, text=True).stdout.split()]


def value(bits):
    return struct.unpack('<f', struct.pack('<I', bits))[0]


def checked(bits, tokens):
    """What the port relies on: 256 positive floats that grow, the last of them 1; each the float nearest its literal."""
    if len(bits) != 256 or bits[255] != 0x3F800000 or any(a >= b for a, b in zip(bits, bits[1:])) or bits[0] != 0x33E4B43E:
        raise ValueError('inverse_db_table is not the table this tool was written for')
    for word, token in zip(bits, tokens):
        if abs(value(word) - float(token[:-1])) > abs(float(token[:-1])) * 1e-7:
            raise ValueError(f'{token} was compiled to {value(word)!r}')
    return bits


def module(bits):
    rows = [', '.join(str(word) for word in bits[start:start + 8]) for start in range(0, 256, 8)]
    return PREAMBLE + '  [' + ',\n    '.join(rows) + ']\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--raylib-source', type=Path, required=True)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = (args.raylib_source / SOURCE).read_text(errors='replace')
    made = module(checked(compiled(text), literals(text)))
    if args.check:
        if not MODULE.is_file() or MODULE.read_text() != made:
            print('src/vorbis_db.bend is stale: run tools/vorbis_db_table.py', file=sys.stderr)
            return 1
        print('src/vorbis_db.bend is current')
        return 0
    MODULE.write_text(made)
    print(f'wrote {MODULE.relative_to(ROOT)}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
