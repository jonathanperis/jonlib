#!/usr/bin/env python3
"""raygui's icon set as src/gui_icons.bend, from the pinned raylib checkout.

    python3 tools/gui_icons.py --raylib-source=RAYLIB            # checks the module
    python3 tools/gui_icons.py --raylib-source=RAYLIB --write    # writes it

raygui.h ships in several example directories of raylib; the `guiIcons` table
(256 icons of 16x16 bits, eight 32-bit words each, two rows a word, low bit
first) must be the same in every copy, or the tool stops. The check (the
`gui-icons` gate) fails when src/gui_icons.bend is not what the pinned
checkout generates.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
START = 'static unsigned int guiIcons[RAYGUI_ICON_MAX_ICONS*RAYGUI_ICON_DATA_ELEMENTS] = {'


def table(header):
    """The 2048 words of one raygui.h."""
    source = header.read_text()
    start = source.index(START)
    words = [int(word, 16) for word in re.findall(r'0x[0-9a-fA-F]{8}', source[start:source.index('};', start)])]
    assert len(words) == 256 * 8, (header, len(words))
    return words


def icons(raylib):
    copies = sorted((raylib / 'examples').glob('*/raygui.h'))
    assert copies, 'no raygui.h under examples/'
    tables = {tuple(table(header)) for header in copies}
    assert len(tables) == 1, 'the copies of raygui.h disagree on guiIcons'
    return list(tables.pop())


def module(words):
    rows = ['  ' + ', '.join(str(word) for word in words[index:index + 8]) for index in range(0, len(words), 8)]
    return '''# Jonlib - zlib license, Copyright (c) 2026 Jonathan Peris.
# raygui's icon set (guiIcons of raygui.h, zlib, Copyright (c) 2014-2026
# Ramon Santamaria (@raysan5); see LICENSES/raygui.txt): 256 icons of 16x16
# bits, eight words each, two rows a word with the low bit first.
# Generated by tools/gui_icons.py from the pinned raylib checkout; do not edit.
import Base

def words() -> +List<U32>:
  [
''' + ',\n'.join('  ' + row for row in rows) + ''']

def head(values: +List<U32>) -> U32:
  match values:
    case Con{value, _}: value
    case Nil{}: 0

# Word `index` (0..7) of icon `id` (0..255).
def word(+id: U32, +index: U32) -> U32:
  head(List.drop(&2, U32, words(), U32.to_nat((8 * id + index : U32))))
'''


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--raylib-source', type=Path, required=True)
    parser.add_argument('--write', action='store_true', help='write src/gui_icons.bend instead of checking it')
    args = parser.parse_args(argv)
    words = icons(args.raylib_source)
    text, target = module(words), ROOT / 'src/gui_icons.bend'
    if args.write:
        target.write_text(text)
        return 0
    if not target.exists() or target.read_text() != text:
        print('gui-icons: FAIL (src/gui_icons.bend is not what tools/gui_icons.py generates from the pinned raygui.h)')
        return 1
    copies = len(list((args.raylib_source / 'examples').glob('*/raygui.h')))
    print(f'gui-icons: PASS (icons={len(words) // 8}, words={len(words)}, set_bits={sum(bin(word).count("1") for word in words)}, '
          f'raygui_copies={copies})')
    return 0


if __name__ == '__main__':
    sys.exit(main())
