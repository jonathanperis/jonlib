import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'tools'))
import mp3_tables as mt


def tables():
    """Tables of the right sizes and the smallest contents verify() accepts: one codebook of five-bit leaves."""
    out = {name: [0] * count for name, (_, count) in mt.TABLES.items()}
    for name, width in (('g_scf_long', 23), ('g_scf_short', 40), ('g_scf_mixed', 40)):
        for at in range(0, len(out[name]), width):
            out[name][at:at + 3] = [200, 200, 176]
    out['tab32'] = [0x88] * 28
    out['tab33'] = [0x0C] * 16
    out['g_drmp3_pow43'] = list(range(145))
    return out


class ProgramTests(unittest.TestCase):
    def test_every_table_is_taken_from_the_header_text(self):
        header = ''.join(f'static const {kind} {name}[{count}] = {{ 1, 2 }};\n' for name, (kind, count) in mt.TABLES.items())
        source = mt.program(header + 'static const float other[2] = { 1.0f, 2.0f };\n')
        self.assertEqual((source.count('static const'), 'other' in source, source.count('memcpy(&w')), (len(mt.TABLES), False, 2))
        with self.assertRaises(ValueError):
            mt.program(header.replace('static const drmp3_int16 tabs[2164]', 'static const drmp3_int16 moved[2164]'))
        with self.assertRaises(ValueError):
            mt.program(header.replace('static const drmp3_uint8 tab33[16]', 'static const float tab33[16]'))

    def test_the_first_declaration_of_a_name_is_the_one_taken(self):
        header = ''.join(f'static const {kind} {name}[{count}] = {{ 7 }};\n' for name, (kind, count) in mt.TABLES.items())
        source = mt.program(header + 'static const drmp3_uint8 g_mod[24] = { 9 };\n')
        self.assertEqual((source.count('t[24] = { 7 }'), source.count('{ 9 }')), (1, 0))

    def test_the_output_is_parsed_with_its_counts(self):
        text = ''.join(f'{name} {count}' + ' 5' * count + '\n' for name, (_, count) in mt.TABLES.items())
        parsed = mt.parse(text)
        self.assertEqual((len(parsed), parsed['g_mod'][:2], len(parsed['tabs'])), (len(mt.TABLES), [5, 5], 2164))
        with self.assertRaises(ValueError):
            mt.parse(text.replace('g_mod 24 5', 'g_mod 23', 1))
        with self.assertRaises(ValueError):
            mt.parse('\n'.join(text.splitlines()[1:]) + '\n')


class VerifyTests(unittest.TestCase):
    def test_what_the_port_relies_on_is_checked(self):
        mt.verify(tables())
        for change in (lambda t: t['g_scf_long'].__setitem__(0, 198),          # 574 values
                       lambda t: t['g_scf_short'].__setitem__(slice(0, 3), [201, 199, 176]),      # an odd band
                       lambda t: t['g_scf_mixed'].__setitem__(5, 2),           # a band after the 0
                       lambda t: t['tabs'].__setitem__(0, -8 * 3000 + 3),      # a walk that leaves tabs
                       lambda t: t['tabs'].__setitem__(0, -8),                 # a walk that peeks no bits
                       lambda t: t['tabs'].__setitem__(0, 6 << 8),             # more bits flushed than peeked
                       lambda t: t['tab32'].__setitem__(0, 0x80),              # a count1 code that peeks no more bits
                       lambda t: t["tab32"].__setitem__(0, 26 << 3 | 3),       # and one sent past the table
                       lambda t: t['g_drmp3_pow43'].pop()):
            changed = tables()
            change(changed)
            with self.assertRaises(ValueError):
                mt.verify(changed)

    def test_a_tree_is_walked_whole(self):
        changed = tables()
        # entry 0 sends on by two bits to entries 32..35; the leaves there are one and two bits long
        changed['tabs'][0] = -(32 << 3) + 2
        changed['tabs'][32:36] = [1 << 8, 1 << 8, 2 << 8 | 0x0F, 2 << 8 | 0xF0]
        changed['tabindex'] = [0] * 32
        changed['g_linbits'] = [0] * 31 + [13]
        depth, code, shift = mt.trees(changed)[0]
        self.assertEqual((depth, code, shift), (2, 7, 7))        # five bits, then two; the code and a sign bit after bs_sh of -1
        self.assertEqual(mt.trees(changed)[31], (2, 7, 19))      # an escaped value flushes 13 linbits before the check
        changed['tabs'][32] = -(32 << 3) + 2                     # a chain that never ends
        with self.assertRaises(ValueError):
            mt.trees(changed)


class RenderTests(unittest.TestCase):
    def test_the_module_names_every_table_and_codebook(self):
        changed = tables()
        changed['tabindex'] = [0] * 16 + [64] * 16
        changed['tabs'][0] = -1
        text = mt.render(changed)
        self.assertTrue(text.startswith('# Generated by tools/mp3_tables.py'))
        self.assertEqual((text.count('\ndef '), 'def tabs.at0()' in text, 'def tabs.at64()' in text), (15, True, True))
        self.assertIn('    case 15: tabs.at0()\n    case 16: tabs.at64()\n', text)
        self.assertIn('    case _: tabs.at64()\n', text)
        self.assertIn('def tabs.at0() -> +List<U32>:\n  [65535, 0, ', text)                # an int16 is its 16-bit pattern
        self.assertEqual(max(len(line) for line in text.splitlines()) <= 170, True)

    def test_rows_and_lines(self):
        self.assertEqual(mt.rows([1, 2, 3, 4], 2), '[[1, 2],\n    [3, 4]]')
        self.assertEqual(mt.flat([1, 2, 3]), '[1, 2, 3]')
        self.assertEqual(mt.flat(list(range(100, 160))).count('\n'), 1)


if __name__ == '__main__':
    unittest.main()
