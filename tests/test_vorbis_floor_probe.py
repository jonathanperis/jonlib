class TableTests(unittest.TestCase):
    TEXT = 'float x;\nstatic float inverse_db_table[256] =\n{\n  ' + ', '.join(['1.5e-07f'] * 255 + ['1.0f']) + '\n};\n'

    def test_the_literals_are_taken_from_the_text(self):
        tokens = dt.literals(self.TEXT)
        self.assertEqual((len(tokens), tokens[0], tokens[255]), (256, '1.5e-07f', '1.0f'))
        with self.assertRaises(ValueError):
            dt.literals(self.TEXT.replace('1.0f', '1.0'))                       # a double is not what the table has
        with self.assertRaises(ValueError):
            dt.literals('static float other[256] = { 1.0f };')

    def test_what_the_port_relies_on(self):
        grows = [0x33E4B43E] + [0x33E4B43E + k for k in range(1, 255)] + [0x3F800000]
        tokens = [f'{dt.value(word):.9e}f' for word in grows]
        self.assertEqual(dt.checked(grows, tokens), grows)
        for wrong in (grows[:-1] + [0x3F800001], [0x33E4B43D] + grows[1:], grows[:5] + [grows[4]] + grows[6:]):
            with self.assertRaises(ValueError):
                dt.checked(wrong, tokens)
        with self.assertRaises(ValueError):
            dt.checked(grows, ['2.0f'] * 256)                                    # a float that is not its literal's

    def test_the_module(self):
        text = dt.module(list(range(256)))
        self.assertTrue(text.startswith('# Generated by tools/vorbis_db_table.py'))
        self.assertIn('def table() -> +List<U32>:\n  [0, 1, 2, 3, 4, 5, 6, 7,\n    8, ', text)
        self.assertTrue(text.endswith('248, 249, 250, 251, 252, 253, 254, 255]\n'))

    def test_the_module_in_the_tree_is_a_generated_one(self):
        text = dt.MODULE.read_text()
        self.assertTrue(text.startswith(dt.PREAMBLE) and text[len(dt.PREAMBLE):].count(',') == 255)
        self.assertEqual((dt.value(870626366) < 1.1e-7, dt.value(1065353216)), (True, 1.0))


class CasesTests(unittest.TestCase):
    def setUp(self):
        rng = Rng(0xF100D)
        self.made = sp.model(sp.stream(third=sp.whole(floors=fp.floors(rng))))
        self.cases = fp.cases(self.made[5], rng)

    def test_the_floors(self):
        self.assertEqual(self.made[:3], (sp.GOING, 0, 5))
        floors = self.made[5]
        self.assertEqual(([len(floor[4]) for floor in floors], {floor[2] for floor in floors}), ([2, 3, 13, 130, 250, 9], {1, 2, 3, 4}))
        self.assertEqual((min(floor[3] for floor in floors), max(floor[3] for floor in floors)), (1, 15))

    def test_the_cases(self):
        self.assertEqual((len(self.cases), {n2 for _, n2, _, _ in self.cases}, {number for number, _, _, _ in self.cases}), (216, {32, 256, 2048}, set(range(6))))
        for number, _, _, ys in self.cases:
            self.assertEqual(len(ys), len(self.made[5][number][4]))
            self.assertTrue(ys[0] >= 0 and all(-32768 <= y <= 32767 for y in ys))

    def test_what_is_refused(self):
        xs, order = [0, 64, 20, 40], [0, 2, 3, 1]
        self.assertFalse(fp.refused(xs, order, 1, [10, 20, 30, 40], 128))
        self.assertTrue(fp.refused(xs, order, 1, [10, 300, 30, 40], 128))            # the last point, at 64, is past the table
        self.assertFalse(fp.refused(xs, order, 1, [10, 300, 30, 40], 64))            # ... and at the half block's end: no level end
        self.assertFalse(fp.refused(xs, order, 1, [10, 300, 30, 40], 32))
        self.assertTrue(fp.refused(xs, order, 4, [10, 64, 30, 40], 128))             # 64 times the multiplier is 256
        self.assertFalse(fp.refused(xs, order, 4, [10, 63, 30, 40], 128))
        self.assertTrue(fp.refused(xs, order, 1, [10, -1, 30, 256], 128))            # the last point with a Y is the one at 40
        self.assertFalse(fp.refused(xs, order, 1, [10, -1, 700, 255], 128))          # a point before the last can be anywhere
        self.assertTrue(fp.refused(xs, order, 1, [256, -1, -1, -1], 128))            # only the first point
        refused = [fp.refused(self.made[5][number][4], self.made[5][number][5], self.made[5][number][2], ys, n2) for number, n2, _, ys in self.cases]
        self.assertTrue(15 <= refused.count(True) <= 60)


if __name__ == '__main__':
    unittest.main()
